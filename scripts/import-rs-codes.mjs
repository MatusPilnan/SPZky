// Imports the Serbian registration areas (регистарска подручја) from sr.wikipedia
// "Регистарске ознаке у Србији" into src/lib/data/rs.generated.ts: code, name (Latin), and
// the map areas (municipalities of the geoBoundaries SRB ADM2 data, OpenStreetMap) each
// area covers, from the table's "Обухваћене општине" column.
//
//   node scripts/import-rs-codes.mjs      # writes the file, prints what didn't match
import { writeFileSync } from 'node:fs';

const LIST = `https://sr.wikipedia.org/w/index.php?title=${encodeURIComponent('Регистарске ознаке у Србији')}&action=raw`;
const MAP = 'https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/SRB/ADM2/geoBoundaries-SRB-ADM2_simplified.geojson';
const headers = { 'User-Agent': 'spz-ky-data-import/1.0 (https://github.com/MatusPilnan/SPZky)' };

const CYR = {
	а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', ђ: 'dj', е: 'e', ж: 'z', з: 'z', и: 'i', ј: 'j', к: 'k', л: 'l', љ: 'lj',
	м: 'm', н: 'n', њ: 'nj', о: 'o', п: 'p', р: 'r', с: 's', т: 't', ћ: 'c', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'c',
	џ: 'dz', ш: 's'
};
/** Cyrillic or Latin with diacritics → plain lower-case ASCII, for matching names. */
const fold = (s) =>
	[...s.toLowerCase()]
		.map((c) => CYR[c] ?? c)
		.join('')
		.replace(/đ/g, 'dj')
		.normalize('NFD')
		.replace(/\p{Diacritic}/gu, '')
		.replace(/[^a-z]/g, '');

const wiki = (await (await fetch(LIST, { headers })).text()).replace(/<!--[\s\S]*?-->/g, '');
const features = (await (await fetch(MAP, { headers })).json()).features;
const areas = features.map((f) => f.properties.shapeName);
/** "Arandjelovac Municipality" / "Cacak City" → "arandjelovac" / "cacak". */
const areaKey = (a) => fold(a.replace(/ (Municipality|City)$/, ''));
const byKey = new Map(areas.map((a) => [areaKey(a), a]));
// Spelled differently (or truncated) in the map data.
byKey.set('petrovac', 'Petrovac-na-Mlavi Municipality');
byKey.set('smederevskapalanka', 'Smederevska Palanka Municipal*');
/** City municipalities that are part of an area already on the map (Novi Sad). */
const PART_OF_CITY = new Set(['petrovaradin']);

const plain = (s) =>
	s
		.replace(/-\{|\}-/g, '')
		.replace(/\[\[([^|\]]*)\|([^\]]*)\]\]/g, '$2')
		.replace(/\[\[([^\]]*)\]\]/g, '$1')
		.replace(/'''?/g, '')
		.trim();
/** Municipalities in a cell: link labels ("[[Општина Бор|Бор]]" → "Бор"). */
const municipalities = (cell) => [...cell.matchAll(/\[\[([^|\]]*)(?:\|([^\]]*))?\]\]/g)].map((m) => (m[2] ?? m[1]).trim());

function tableRows(section) {
	const start = wiki.indexOf(section);
	const end = wiki.indexOf('|}', start);
	return wiki
		.slice(start, end)
		.split('\n|-')
		.slice(1)
		.map((r) =>
			r
				.split(/\n/)
				.filter((l) => l.startsWith('|'))
				.flatMap((l) => l.slice(1).split('||'))
				.map((c) => c.trim())
		)
		.filter((cells) => cells.length >= 4);
}

const out = [];
const unmatched = [];
for (const [section, rare] of [
	['== Ознаке на стандардним таблицама ==', false],
	['Бивше ознаке на Косову и Метохији', true]
]) {
	for (const cells of tableRows(section)) {
		// Codes are Latin; the source writes a few with look-alike Cyrillic letters (КМ).
		const code = plain(cells[0]).replace(/[АВЕКМНОРСТХ]/g, (c) => 'ABEKMHOPCTX'['АВЕКМНОРСТХ'.indexOf(c)]);
		const name = plain(cells[1]);
		const mapped = [];
		for (const m of municipalities(cells[3])) {
			// Belgrade's city municipalities are one area on the map.
			const key = /Градска општина/.test(cells[3]) && code === 'BG' ? 'belgrade' : fold(m);
			const area = byKey.get(key);
			if (area) mapped.push(area);
			else if (!rare && !PART_OF_CITY.has(key)) unmatched.push(`${code}: ${m}`);
		}
		out.push({ code, name, areas: [...new Set(mapped)], ...(rare ? { rare: true } : {}) });
	}
}

const used = new Set(out.flatMap((r) => r.areas));
const ts = `// GENERATED by scripts/import-rs-codes.mjs from sr.wikipedia "Регистарске ознаке у Србији"
// (imported ${new Date().toISOString().slice(0, 10)}). Do not edit; see src/lib/data/rs.ts for sources and decisions.
export const rsTable: { code: string; name: string; areas: string[]; rare?: boolean }[] = ${JSON.stringify(out, null, '\t')};
`;
writeFileSync('src/lib/data/rs.generated.ts', ts);
console.log(`codes: ${out.length} (rare: ${out.filter((r) => r.rare).length})`);
console.log('unmatched municipalities:', unmatched.join(' | ') || '–');
console.log('map areas without a code:', areas.filter((a) => !used.has(a)).join(' | ') || '–');
