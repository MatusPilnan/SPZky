// Generates src/lib/geo/maps/continents.ts: one map per continent for Home, with every
// supported country as its own shape (coloured by progress in the app) and all other land
// as one untracked background shape.
//
//   node scripts/build-continents.mjs
//
// Source: Natural Earth 1:50m admin-0 countries (public domain) via world-atlas. Each map
// is a rectangle in Lambert azimuthal equal-area around the continent, so neighbouring
// land (e.g. Turkey, North Africa next to Europe) is drawn as untracked. A continent is
// written only if at least one supported country (scripts/countries.mjs) lies in it; add
// a frame below when a country on a new continent gets a collection.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import mapshaper from 'mapshaper';
import { feature } from 'topojson-client';
import { COUNTRIES, countryOfFeature } from './countries.mjs';

/** Frames: projection centre [lon, lat] and the rectangle around it in km (x right, y up). */
const CONTINENTS = [
	{ id: 'europe', center: [15, 53], x: [-2600, 2800], y: [-2250, 2300] }
];
const WIDTH = 1000;

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf-8'));
const world = feature(topology, topology.objects.countries);
for (const f of world.features) f.properties = { code: countryOfFeature(f) ?? '' };

const round = (n) => Math.round(n * 10) / 10;
function toPath(geometry, project) {
	const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
	let d = '';
	for (const rings of polygons)
		for (const ring of rings) {
			const pts = ring.map(project);
			d += 'M' + pts.map(([x, y]) => `${x} ${y}`).join(' ') + 'Z';
		}
	return d;
}

const out = [];
for (const c of CONTINENTS) {
	const [x0, x1] = c.x.map((v) => v * 1000);
	const [y0, y1] = c.y.map((v) => v * 1000);
	const proj = `+proj=laea +lat_0=${c.center[1]} +lon_0=${c.center[0]} +datum=WGS84`;
	// Project, cut out the frame, then simplify (topology-aware: shared borders stay shared).
	const res = await mapshaper.applyCommands(
		`-i in.json -proj ${proj} -clip bbox=${x0},${y0},${x1},${y1} remove-slivers -simplify 12% keep-shapes -o out.json format=geojson`,
		{ 'in.json': JSON.stringify(world) }
	);
	const features = JSON.parse(res['out.json']).features.filter((f) => f.geometry);
	const scale = WIDTH / (x1 - x0);
	const height = Math.round((y1 - y0) * scale);
	const project = ([x, y]) => [round((x - x0) * scale), round((y1 - y) * scale)];

	const countries = features
		.filter((f) => f.properties.code)
		.map((f) => ({ code: f.properties.code, d: toPath(f.geometry, project) }))
		.sort((a, b) => a.code.localeCompare(b.code));
	if (countries.length === 0) continue;
	const land = features
		.filter((f) => !f.properties.code)
		.map((f) => toPath(f.geometry, project))
		.join('');
	out.push({ id: c.id, viewBox: `0 0 ${WIDTH} ${height}`, countries, land });
	console.log(`${c.id}: ${countries.length} tracked countries (${countries.map((x) => x.code).join(' ')})`);
}

const missing = Object.keys(COUNTRIES).filter((code) => !out.some((c) => c.countries.some((x) => x.code === code)));
if (missing.length) throw new Error(`no continent frame contains ${missing.join(', ')}: add or widen one in CONTINENTS`);

const ts = `// GENERATED by scripts/build-continents.mjs. Do not edit.
// Natural Earth 1:50m countries (public domain) via world-atlas, simplified with mapshaper.
import type { ContinentMapData } from './types';

export const continents: ContinentMapData[] = ${JSON.stringify(out)};
`;
writeFileSync('src/lib/geo/maps/continents.ts', ts);
console.log(`wrote src/lib/geo/maps/continents.ts, ${Math.round(ts.length / 1024)} kB`);
