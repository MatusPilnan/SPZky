// Generates src/lib/geo/borders.ts: country outlines for the offline
// "which country am I in" lookup (GPS → default country choice).
//
//   node scripts/build-borders.mjs [10m|50m|110m]
//
// Source: Natural Earth admin-0 countries (public domain) via the world-atlas
// package. Coordinates are rounded to 3 decimals (~100 m), which is far below
// the dataset's own accuracy. Add countries by ISO 3166-1 numeric code below.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const COUNTRIES = { SK: '703', CZ: '203' };
const resolution = process.argv[2] ?? '10m';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve(`world-atlas/countries-${resolution}.json`), 'utf-8'));
const all = feature(topology, topology.objects.countries).features;

const round = (n) => Math.round(n * 1000) / 1000;
const out = {};
let points = 0;

for (const [code, id] of Object.entries(COUNTRIES)) {
	const f = all.find((x) => String(x.id).padStart(3, '0') === id);
	if (!f) throw new Error(`country ${code} (${id}) not found`);
	const polygons = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
	out[code] = polygons.map((rings) =>
		rings.map((ring) => {
			const pts = [];
			for (const [lng, lat] of ring) {
				const p = [round(lng), round(lat)];
				const prev = pts[pts.length - 1];
				if (!prev || prev[0] !== p[0] || prev[1] !== p[1]) pts.push(p);
			}
			points += pts.length;
			return pts;
		})
	);
}

const header = `// GENERATED by scripts/build-borders.mjs (Natural Earth ${resolution}, public domain). Do not edit.
// Per country: polygons → rings (first = outer, rest = holes) → [lng, lat] points.
`;
const body = `export type Ring = [number, number][];
export type CountryShape = Ring[][];

export const borders: Record<string, CountryShape> = ${JSON.stringify(out)};
`;
writeFileSync('src/lib/geo/borders.ts', header + body);
console.log(`wrote src/lib/geo/borders.ts: ${Object.keys(out).join(', ')}, ${points} points (${resolution})`);
